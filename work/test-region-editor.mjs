import assert from 'node:assert/strict';
import fs from 'node:fs';
import {validPolygon,cleanRegions,RegionHistory} from '../outputs/zerozone-haritalar/region-model.js';
const square=[{x:.1,y:.1},{x:.3,y:.1},{x:.3,y:.3},{x:.1,y:.3}];
const triangle=[{x:.5,y:.5},{x:.7,y:.5},{x:.6,y:.7}];
const region={id:'sample',name:'Örnek',points:square};
const a=new RegionHistory({regions:[]}),b=new RegionHistory({regions:[]});
a.commit({regions:[region]});assert.equal(a.value.regions.length,1);assert.equal(b.value.regions.length,0);
a.commit({...a.value,visible:false,regions:[{...region,visible:false}]});assert.equal(a.value.visible,false);
assert.deepEqual(new RegionHistory(JSON.parse(JSON.stringify(a.value))).value,a.value,'reload preserves visibility and geometry');
a.commit({...a.value,regions:[{...region,points:triangle}]});assert.deepEqual(a.value.regions[0].points,triangle);
a.undo();assert.deepEqual(a.value.regions[0].points,square);a.redo();assert.deepEqual(a.value.regions[0].points,triangle);
a.commit({...a.value,regions:[]});a.undo();assert.equal(a.value.regions.length,1,'deleted region recovers');
a.commit({regions:[region]});a.undo();assert.deepEqual(a.value.regions[0].points,triangle,'restore is reversible');
assert.equal(validPolygon([square[0],square[2],square[1],square[3]]),false,'reject bow tie');
assert.equal(validPolygon([{x:0,y:0},{x:.1,y:.1},{x:.2,y:.2}]),false);
assert.equal(validPolygon([{x:-1,y:0},...square]),false);
assert.throws(()=>cleanRegions({regions:[{...region,points:[{x:NaN,y:.1},...square]}]}));
assert.throws(()=>cleanRegions({regions:[region,region]}));
const base=JSON.parse(fs.readFileSync(new URL('../outputs/zerozone-haritalar/data/red-zones.json',import.meta.url)));
for(const data of Object.values(base.layers))assert.equal(cleanRegions(data).regions.length,2);
console.log('PASS: custom region creation/redraw, visibility persistence, layer isolation, undo/redo/delete/restore, invalid polygons, all 64 reference regions editable.');
